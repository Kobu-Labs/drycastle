"""glTF binary (.glb) reading and writing for the model scripts."""
import json
import math
import struct
from pathlib import Path

from meshkit import cross, sub, turn, unit


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def pbr_material(name, rgb, rough, metal, emis=0, alpha=1.0, double_sided=False):
    """A glTF material from sRGB colour. emis > 0: emissive in the same colour at that strength. alpha < 1: blended and double sided."""
    lin = [round(srgb_to_linear(v), 4) for v in rgb]
    m = {"name": name, "pbrMetallicRoughness": {"baseColorFactor": lin + [alpha], "metallicFactor": metal, "roughnessFactor": rough}}
    if emis:
        m["emissiveFactor"] = [round(v * emis, 4) for v in lin]
    if alpha < 1:
        m["alphaMode"] = "BLEND"
        double_sided = True
    if double_sided:
        m["doubleSided"] = True
    return m


def materials_from(table, double_sided=False):
    """{name: (r, g, b, roughness, metallic[, emissive strength[, alpha]])} -> glTF materials, in table order."""
    return [pbr_material(name, spec[:3], *spec[3:], double_sided=double_sided) for name, spec in table.items()]


def write_glb(root, path, materials, generator, scene_name=None):
    """Writes the Node tree `root` (meshkit.Node) as one .glb: one mesh per node that has triangles, one primitive per material; a node has a
    translation and, when its yaw differs from its parent's, a rotation about Y (its vertices are stored in its own frame). `materials`: glTF material dicts; a triangle's material name picks one."""
    buf = bytearray()
    views, accessors, meshes, nodes = [], [], [], []
    mat_names = [m["name"] for m in materials]
    turned = any(n.yaw for n in root.walk())     # a model with a turned node stores every node in its own frame

    def view(data, target):
        while len(buf) % 4:
            buf.append(0)
        views.append({"buffer": 0, "byteOffset": len(buf), "byteLength": len(data), "target": target})
        buf.extend(data)
        return len(views) - 1

    def primitive(node, mi, mname):
        verts, lookup, idx = [], {}, []
        for m, ps, nr in node.tris:
            if m != mname:
                continue
            fn = unit(cross(sub(ps[1], ps[0]), sub(ps[2], ps[0])))
            for k in range(3):
                p, n = sub(ps[k], node.origin), nr[k] if nr else fn
                if turned:
                    p, n = turn(p, -node.yaw), turn(n, -node.yaw)
                key = tuple(round(v, 5) for v in p) + tuple(round(v, 3) for v in n)
                if key not in lookup:
                    lookup[key] = len(verts)
                    verts.append((p, n))
                idx.append(lookup[key])
        if not idx:
            return None
        assert len(verts) < 65536
        pos = b"".join(struct.pack("<3f", *p) for p, _ in verts)
        nor = b"".join(struct.pack("<3f", *n) for _, n in verts)
        lo = [struct.unpack("<f", struct.pack("<f", min(p[i] for p, _ in verts)))[0] for i in range(3)]
        hi = [struct.unpack("<f", struct.pack("<f", max(p[i] for p, _ in verts)))[0] for i in range(3)]
        accessors.append({"bufferView": view(pos, 34962), "componentType": 5126, "count": len(verts), "type": "VEC3", "min": lo, "max": hi})
        accessors.append({"bufferView": view(nor, 34962), "componentType": 5126, "count": len(verts), "type": "VEC3"})
        accessors.append({"bufferView": view(struct.pack(f"<{len(idx)}H", *idx), 34963), "componentType": 5123, "count": len(idx), "type": "SCALAR"})
        a = len(accessors)
        return {"attributes": {"POSITION": a - 3, "NORMAL": a - 2}, "indices": a - 1, "material": mi}

    def emit(node, parent):
        entry = {"name": node.name}
        t = sub(node.origin, parent.origin) if parent else node.origin
        if parent and turned:
            t = turn(t, -parent.yaw)
        if any(abs(v) > 1e-9 for v in t):
            entry["translation"] = [round(v, 5) + 0.0 for v in t]   # + 0.0: no "-0.0" in the file
        rel = node.yaw - (parent.yaw if parent else 0.0)
        if abs(rel) > 1e-9:
            entry["rotation"] = [0.0, round(math.sin(math.radians(rel) / 2), 6), 0.0, round(math.cos(math.radians(rel) / 2), 6)]
        index = len(nodes)
        nodes.append(entry)
        if node.tris:
            prims = [p for mi, mname in enumerate(mat_names) if (p := primitive(node, mi, mname))]
            entry["mesh"] = len(meshes)
            meshes.append({"name": node.name, "primitives": prims})
        kids = [emit(c, node) for c in node.children]
        if kids:
            entry["children"] = kids
        return index

    top = emit(root, None)
    while len(buf) % 4:
        buf.append(0)
    gltf = {"asset": {"version": "2.0", "generator": generator, "copyright": "CC0 1.0, generated by the project's own script"},
            "scene": 0, "scenes": [{"name": scene_name or root.name, "nodes": [top]}], "nodes": nodes, "meshes": meshes, "materials": materials,
            "accessors": accessors, "bufferViews": views, "buffers": [{"byteLength": len(buf)}]}
    js = json.dumps(gltf, separators=(",", ":")).encode()
    js += b" " * (-len(js) % 4)
    out = struct.pack("<4sII", b"glTF", 2, 12 + 8 + len(js) + 8 + len(buf)) + struct.pack("<I4s", len(js), b"JSON") + js + struct.pack("<I4s", len(buf), b"BIN\0") + bytes(buf)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_bytes(out)


def read_glb(path):
    """(json document, binary chunk) of a .glb."""
    raw = Path(path).read_bytes()
    assert raw[:4] == b"glTF", path
    at, doc, blob = 12, None, b""
    while at < len(raw):
        size, kind = struct.unpack_from("<II", raw, at)
        chunk = raw[at + 8:at + 8 + size]
        if kind == 0x4E4F534A:
            doc = json.loads(chunk)
        elif kind == 0x004E4942:
            blob = chunk
        at += 8 + size
    return doc, blob
