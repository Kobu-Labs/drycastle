    static MeadowFile Load() => MeadowFile.Parse(Convert.FromBase64String(FileB64));

    [Fact]
    public void HashMatchesThePipeline()
    {
        foreach (var (ix, iy, salt, expected) in Hashes)
            Assert.Equal(expected, MeadowGen.Hash01(ix, iy, salt), 12);
    }

    [Fact]
    public void HeaderAndLayers()
    {
        var f = Load();
        Assert.Equal(2f, f.CellM);
        Assert.Equal(4, f.CellsPerChunk);
        Assert.Equal(0.85f, f.JitterM, 4);
        Assert.Equal(0.7f, f.TrunkReachM, 4);
        Assert.Equal(3, f.ChunkCount);
        Assert.Equal(new[] { "tuft", "litter" }, f.Layers.Select(l => l.Name));
        Assert.Equal("stick", f.Layers[1].AltKind);
    }

    [Fact]
    public void InstancesMatchThePipeline()
    {
        var f = Load();
        var got = new List<MeadowInstance>();
        for (var li = 0; li < f.Layers.Count; li++)
            for (var gy = -4; gy < 4; gy++)
                for (var gx = -4; gx < 4; gx++) MeadowGen.Cell(f, li, gx, gy, got);
        var want = JsonDocument.Parse(ExpectedJson).RootElement.EnumerateArray()
            .Select(e => new MeadowInstance(e[0].GetString()!, e[1].GetSingle(), e[2].GetSingle(), e[3].GetSingle(), e[4].GetSingle())).ToList();
        Assert.Equal(want.Count, got.Count);
        var sorted = got.OrderBy(i => i.Kind, StringComparer.Ordinal).ThenBy(i => Math.Round(i.X, 3)).ThenBy(i => Math.Round(i.Y, 3)).ToList();
        for (var k = 0; k < want.Count; k++)
        {
            Assert.Equal(want[k].Kind, sorted[k].Kind);
            Assert.Equal(want[k].X, sorted[k].X, 3);
            Assert.Equal(want[k].Y, sorted[k].Y, 3);
            Assert.Equal(want[k].Rot, sorted[k].Rot, 3);
            Assert.Equal(want[k].Scale, sorted[k].Scale, 3);
        }
    }

    [Fact]
    public void TilesAddUpToCellsAndAreDeterministic()
    {
        var f = Load();
        var a = new List<MeadowInstance>(); var b = new List<MeadowInstance>(); var cells = new List<MeadowInstance>();
        MeadowGen.Tile(f, 0, -1, -1, 4, a);
        MeadowGen.Tile(f, 0, -1, -1, 4, b);
        for (var gy = -4; gy < 0; gy++) for (var gx = -4; gx < 0; gx++) MeadowGen.Cell(f, 0, gx, gy, cells);
        Assert.Equal(a, b);
        Assert.Equal(cells, a);
    }

    [Fact]
    public void NothingWhereTheRasterIsEmpty()
    {
        var f = Load();
        var got = new List<MeadowInstance>();
        MeadowGen.Tile(f, 0, 5, 5, 4, got); // chunk (1, 1) is not in the file
        MeadowGen.Tile(f, 1, -3, -3, 4, got);
        Assert.Empty(got);
        Assert.Equal(0, f.Density(0, 100, 100));
    }

    [Fact]
    public void LiveCapStopsAGrowingLayer()
    {
        Assert.True(MeadowSettings.HasRoom("tuft", 1f, 0));
        Assert.True(MeadowSettings.HasRoom("tuft", 1f, MeadowSettings.CapOf("tuft") - 1));
        Assert.False(MeadowSettings.HasRoom("tuft", 1f, MeadowSettings.CapOf("tuft")));
        Assert.False(MeadowSettings.HasRoom("tuft", 0.5f, MeadowSettings.CapOf("tuft") / 2));
    }

    [Fact]
    public void BadFilesAreRefused()
    {
        Assert.Throws<FormatException>(() => MeadowFile.Parse(new byte[] { 1, 2, 3 }));
        var bytes = Convert.FromBase64String(FileB64);
        Assert.Throws<FormatException>(() => MeadowFile.Parse(bytes.Take(40).ToArray()));
        bytes[4] = 9; // format version
        Assert.Throws<FormatException>(() => MeadowFile.Parse(bytes));
    }
