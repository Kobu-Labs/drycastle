using System.Text.Json;
using Godot;

namespace Suchohrad.MapLoader;

/// <summary>Result of <see cref="MapLoader.ApplyRegions"/>: the region IDs whose baked nodes were hidden and the new nodes added.</summary>
public sealed record RegionResult(IReadOnlyList<string> Replaced, int Nodes);

// Regions: hand-drawn colour shapes (nodes "region_<ID>", visual only, no collision). The exported chunk files hold
// one node per chunk file a region touches, so the baked side is a list per ID. A region-run summary swaps them.
public sealed partial class MapLoader
{
    // region id -> baked nodes from the chunk files (several when the region crosses a chunk border)
    readonly Dictionary<string, List<MeshInstance3D>> _bakedRegions = new();
    // region id -> container of the regenerated node of that region (child of Root)
    readonly Dictionary<string, Node3D> _dynamicRegions = new();

    /// <summary>Baked region nodes by region ID (the chunk files' own nodes; hidden once the region was swapped).</summary>
    public IReadOnlyDictionary<string, List<MeshInstance3D>> BakedRegions => _bakedRegions;
    /// <summary>Containers ("dyn_region_&lt;ID&gt;") of regions regenerated by <see cref="ApplyRegions"/>.</summary>
    public IReadOnlyDictionary<string, Node3D> DynamicRegions => _dynamicRegions;

    static string? RegionId(string nodeName)
        => nodeName.StartsWith("region_") && nodeName.Length > "region_".Length && !nodeName.EndsWith("_collision")
            ? nodeName["region_".Length..] : null;

    void RegisterBakedRegion(string id, MeshInstance3D mi)
    {
        if (!_bakedRegions.TryGetValue(id, out var l)) _bakedRegions[id] = l = new();
        l.Add(mi);
    }

    /// <summary>Region IDs that currently show something (baked and not swapped, or regenerated).</summary>
    public IEnumerable<string> VisibleRegionIds()
        => _bakedRegions.Where(kv => kv.Value.Any(m => GodotObject.IsInstanceValid(m) && m.Visible)).Select(kv => kv.Key)
            .Concat(_dynamicRegions.Keys).Distinct().OrderBy(x => x, StringComparer.Ordinal);

    /// <summary>
    /// Apply a region-run summary (JSON from --out, with its --glb): for every ID in "replaces" hide all baked
    /// "region_&lt;ID&gt;" nodes (one per chunk file) and free the previous regenerated node, then add the GLB's
    /// "region_&lt;ID&gt;" nodes. Deleted regions are only hidden. Safe to repeat; nothing is changed if the summary
    /// or the GLB cannot be read. Baked nodes are hidden, never freed (they belong to the chunk files); regenerated
    /// ones are detached and queued for freeing exactly once.
    /// </summary>
    /// <summary>Parse a region-run summary and its GLB without changing the map; throws exactly when ApplyRegions would before touching anything.</summary>
    public void ValidateRegions(string summaryJsonPath)
    {
        string glbPath;
        using (var doc = JsonDocument.Parse(File.ReadAllText(summaryJsonPath)))
        {
            var r = doc.RootElement;
            _ = r.GetProperty("replaces").EnumerateArray().Select(e => e.GetString()!).ToList();
            glbPath = r.TryGetProperty("glb", out var g) && g.ValueKind == JsonValueKind.String ? g.GetString()! : "";
        }
        if (glbPath != "") LoadGltf(glbPath).Free();
    }

    public RegionResult ApplyRegions(string summaryJsonPath)
    {
        GeometryChanged();
        string glbPath;
        List<string> replaces;
        using (var doc = JsonDocument.Parse(File.ReadAllText(summaryJsonPath)))
        {
            var r = doc.RootElement;
            replaces = r.GetProperty("replaces").EnumerateArray().Select(e => e.GetString()!).ToList();
            glbPath = r.TryGetProperty("glb", out var g) && g.ValueKind == JsonValueKind.String ? g.GetString()! : "";
        }
        Node3D? scene = glbPath != "" ? LoadGltf(glbPath) : null; // before touching anything
        var set = replaces.ToHashSet();
        foreach (var id in replaces)
        {
            RemoveDynamicRegion(id);
            if (_bakedRegions.TryGetValue(id, out var baked))
                foreach (var mi in baked) if (GodotObject.IsInstanceValid(mi)) mi.Visible = false;
        }
        var nodes = 0;
        if (scene != null)
        {
            foreach (var mi in AllMeshes(scene).ToList())
            {
                if (mi.Mesh == null || RegionId(mi.Name.ToString()) is not { } id) continue;
                if (!set.Contains(id)) { Warn($"region GLB has {id}, which is not in 'replaces'; ignored"); continue; }
                if (_dynamicRegions.ContainsKey(id)) { Warn($"region GLB has {id} twice; the second one is ignored"); continue; }
                var container = new Node3D { Name = $"dyn_region_{id}" };
                Root.AddChild(container);
                _dynamicRegions[id] = container;
                mi.GetParent().RemoveChild(mi);
                mi.Owner = null;
                container.AddChild(mi);
                mi.Transform = Transform3D.Identity;
                FixMaterials(mi);
                nodes++;
            }
            scene.Free();
        }
        return new RegionResult(replaces, nodes);
    }

    void RemoveDynamicRegion(string id)
    {
        GeometryChanged();
        if (!_dynamicRegions.Remove(id, out var c)) return;
        c.GetParent()?.RemoveChild(c);
        c.QueueFree();
    }
}
