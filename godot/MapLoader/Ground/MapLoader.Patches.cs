using System.Text.Json;
using Godot;
using Drycastle.MapLoader.Ground;

namespace Drycastle.MapLoader;

// Ground patches: hand-drawn ground (GLOSSARY "Ground patch"; nodes "patch_<ID>", visual only, no collision). Until the next
// full map build a patch shows as paint in its type's first terrain colour. The exported chunk files hold one node per chunk
// file a patch touches, so the baked side is a list per ID. A patch-run summary swaps them.
public sealed partial class MapLoader
{
    // patch id -> baked nodes from the chunk files (several when the patch crosses a chunk border)
    readonly Dictionary<string, List<MeshInstance3D>> _bakedPatches = new();
    // patch id -> container of the regenerated node of that patch (child of Root)
    readonly Dictionary<string, Node3D> _dynamicPatches = new();

    /// <summary>Baked patch nodes by patch ID (the chunk files' own nodes; hidden once the patch was swapped).</summary>
    public IReadOnlyDictionary<string, List<MeshInstance3D>> BakedPatches => _bakedPatches;
    /// <summary>Containers ("dyn_patch_&lt;ID&gt;") of patches regenerated by <see cref="ApplyPatches"/>.</summary>
    public IReadOnlyDictionary<string, Node3D> DynamicPatches => _dynamicPatches;

    static string? PatchId(string nodeName)
        => nodeName.StartsWith("patch_") && nodeName.Length > "patch_".Length && !nodeName.EndsWith("_collision")
            ? nodeName["patch_".Length..] : null;

    void RegisterBakedPatch(string id, MeshInstance3D mi)
    {
        if (!_bakedPatches.TryGetValue(id, out var l)) _bakedPatches[id] = l = new();
        l.Add(mi);
    }

    /// <summary>Patch IDs that currently show something (baked and not swapped, or regenerated).</summary>
    public IEnumerable<string> VisiblePatchIds()
        => _bakedPatches.Where(kv => kv.Value.Any(m => GodotObject.IsInstanceValid(m) && m.Visible)).Select(kv => kv.Key)
            .Concat(_dynamicPatches.Keys).Distinct().OrderBy(x => x, StringComparer.Ordinal);

    /// <summary>Parse a patch-run summary and its GLB without changing the map; throws exactly when ApplyPatches would before touching anything.</summary>
    public void ValidatePatches(string summaryJsonPath)
    {
        string glbPath;
        using (var doc = JsonDocument.Parse(File.ReadAllText(summaryJsonPath)))
        {
            var r = doc.RootElement;
            _ = r.GetProperty("replaces").EnumerateArray().Select(e => e.GetString()!).ToList();
            glbPath = r.TryGetProperty("glb", out var g) && g.ValueKind == JsonValueKind.String ? g.GetString()! : "";
        }
        if (glbPath != "") LoadGltf(glbPath).Free();
    }

    /// <summary>
    /// Apply a patch-run summary (JSON from --out, with its --glb): for every ID in "replaces" hide all baked
    /// "patch_&lt;ID&gt;" nodes (one per chunk file) and free the previous regenerated node, then add the GLB's
    /// "patch_&lt;ID&gt;" nodes. Deleted patches are only hidden. Safe to repeat; nothing is changed if the summary
    /// or the GLB cannot be read. Baked nodes are hidden, never freed (they belong to the chunk files); regenerated
    /// ones are detached and queued for freeing exactly once.
    /// </summary>
    public PatchResult ApplyPatches(string summaryJsonPath)
    {
        GeometryChanged();
        string glbPath;
        List<string> replaces;
        using (var doc = JsonDocument.Parse(File.ReadAllText(summaryJsonPath)))
        {
            var r = doc.RootElement;
            replaces = r.GetProperty("replaces").EnumerateArray().Select(e => e.GetString()!).ToList();
            glbPath = r.TryGetProperty("glb", out var g) && g.ValueKind == JsonValueKind.String ? g.GetString()! : "";
        }
        Node3D? scene = glbPath != "" ? LoadGltf(glbPath) : null; // before touching anything
        var set = replaces.ToHashSet();
        foreach (var id in replaces)
        {
            RemoveDynamicPatch(id);
            if (_bakedPatches.TryGetValue(id, out var baked))
                foreach (var mi in baked) if (GodotObject.IsInstanceValid(mi)) mi.Visible = false;
        }
        var nodes = 0;
        if (scene != null)
        {
            foreach (var mi in AllMeshes(scene).ToList())
            {
                if (mi.Mesh == null || PatchId(mi.Name.ToString()) is not { } id) continue;
                if (!set.Contains(id)) { Warn($"patch GLB has {id}, which is not in 'replaces'; ignored"); continue; }
                if (_dynamicPatches.ContainsKey(id)) { Warn($"patch GLB has {id} twice; the second one is ignored"); continue; }
                var container = new Node3D { Name = $"dyn_patch_{id}" };
                Root.AddChild(container);
                _dynamicPatches[id] = container;
                mi.GetParent().RemoveChild(mi);
                mi.Owner = null;
                container.AddChild(mi);
                mi.Transform = Transform3D.Identity;
                FixMaterials(mi);
                nodes++;
            }
            scene.Free();
        }
        return new PatchResult(replaces, nodes);
    }

    void RemoveDynamicPatch(string id)
    {
        GeometryChanged();
        if (!_dynamicPatches.Remove(id, out var c)) return;
        c.GetParent()?.RemoveChild(c);
        c.QueueFree();
    }
}
