namespace Drycastle.ShooterCore;

/// <summary>What an icon is for. Each kind has its own folder under ui/icons.</summary>
public enum IconKind { Weapon, Category, Perk, Streak, Item }

/// <summary>
/// Maps a data id (weapon, weapon category, perk, killstreak, item) to its icon file under <c>res://ui/icons/</c>.
/// Scene-free: the Godot side passes its own existence check. An id with no icon resolves to <see cref="Placeholder"/>, an item with none to
/// <see cref="ItemFallback"/> (a generic item glyph, so an item added without art still reads as an item).
/// Files are named by id: <c>weapons/&lt;id&gt;.png</c> (512x256), <c>categories/&lt;category&gt;.png</c>,
/// <c>perks/&lt;id&gt;.png</c>, <c>streaks/&lt;id&gt;.png</c>, <c>items/&lt;id&gt;.png</c> (128x128). Generated by <c>godot/shooter/tools</c>.
/// </summary>
public sealed class IconRegistry
{
    public const string Root = "res://ui/icons/";
    public const string Placeholder = Root + "placeholder.png";
    /// <summary>What an item without an icon of its own shows (not in <c>items/</c>, so no item id can collide with it).</summary>
    public const string ItemFallback = Root + "item_fallback.png";

    readonly IReadOnlyDictionary<IconKind, IReadOnlySet<string>> _ids;

    /// <summary>Icons for every id in the given data. Categories come from the weapons' categories.</summary>
    public IconRegistry(GameData data)
        : this(
            data.Weapons.Weapons.Select(w => w.Id),
            data.Weapons.Weapons.Select(w => CategoryId(w.Category)).OfType<string>(),
            data.Perks.Perks.Select(p => p.Id),
            data.Killstreaks.Streaks.Select(s => s.Id),
            data.Items.Items.Select(i => i.Id))
    {
    }

    public IconRegistry(IEnumerable<string> weaponIds, IEnumerable<string> categoryIds, IEnumerable<string> perkIds, IEnumerable<string> streakIds, IEnumerable<string>? itemIds = null)
    {
        _ids = new Dictionary<IconKind, IReadOnlySet<string>>
        {
            [IconKind.Weapon] = new HashSet<string>(weaponIds, StringComparer.Ordinal),
            [IconKind.Category] = new HashSet<string>(categoryIds, StringComparer.Ordinal),
            [IconKind.Perk] = new HashSet<string>(perkIds, StringComparer.Ordinal),
            [IconKind.Streak] = new HashSet<string>(streakIds, StringComparer.Ordinal),
            [IconKind.Item] = new HashSet<string>(itemIds ?? Array.Empty<string>(), StringComparer.Ordinal),
        };
    }

    /// <summary>The snake_case id a category's badge is stored under; null for categories without a badge (launcher, melee).</summary>
    public static string? CategoryId(WeaponCategory category) => category switch
    {
        WeaponCategory.Pistol => "pistol",
        WeaponCategory.MachineGun => "machine_gun",
        WeaponCategory.AssaultRifle => "assault_rifle",
        WeaponCategory.Smg => "smg",
        WeaponCategory.Shotgun => "shotgun",
        WeaponCategory.Sniper => "sniper",
        _ => null,
    };

    public static string Folder(IconKind kind) => kind switch
    {
        IconKind.Weapon => "weapons",
        IconKind.Category => "categories",
        IconKind.Perk => "perks",
        IconKind.Streak => "streaks",
        IconKind.Item => "items",
        _ => throw new ArgumentOutOfRangeException(nameof(kind)),
    };

    /// <summary>The file an id's icon is stored in, whether or not it exists.</summary>
    public static string PathFor(IconKind kind, string id) => $"{Root}{Folder(kind)}/{id}.png";

    /// <summary>True when the data has this id (the icon file is expected to exist too; a test checks that).</summary>
    public bool Knows(IconKind kind, string id) => _ids[kind].Contains(id);

    /// <summary>
    /// The icon for an id: its file when the id is known and <paramref name="exists"/> (when given) accepts the path,
    /// otherwise <see cref="Placeholder"/> (<see cref="ItemFallback"/> for an item). Null id (no category badge) is the placeholder.
    /// </summary>
    public string Resolve(IconKind kind, string? id, Func<string, bool>? exists = null)
    {
        var fallback = kind == IconKind.Item ? ItemFallback : Placeholder;
        if (id is null || !Knows(kind, id)) return fallback;
        var path = PathFor(kind, id);
        return exists is null || exists(path) ? path : fallback;
    }
}
